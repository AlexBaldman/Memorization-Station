import * as React from "react"

import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { noHover?: boolean }
>(({ className, noHover = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border-4 border-black bg-card text-card-foreground shadow-[8px_8px_0px_var(--shadow-color)] transition-all duration-200 ease-in-out",
      !noHover && "hover:shadow-[12px_12px_0px_var(--shadow-color)] hover:-translate-y-1.5",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

